/**
 * Ghost OCR Data Filter — Extracted from useOCRTextLayerStore
 * 
 * Targeted filter for PaddleOCR / EasyOCR ghost border noise artifacts and spiky balloon edge artifacts.
 */

import type { OCRLine, OCRWord, OCREngine, OCRDroppedWord } from '../../types';
import { isKnownShortWordHelper } from './ocrSafetyLineDedup';

export interface GhostFilterResult {
  lines: OCRLine[];
  words: OCRWord[];
  droppedWords?: OCRDroppedWord[];
  dropCounts?: Record<string, number>;
}

interface GhostCheckResult {
  isGhost: boolean;
  reason?: string;
  dropCountKey?: string;
}

function checkGhostNoiseReason(
  line: OCRLine | undefined,
  isExternal: boolean,
  dpiScale: number
): GhostCheckResult {
  if (!line) return { isGhost: true, reason: 'emptyLine', dropCountKey: 'ghostEmptyLineDrop' };
  const text = String(line.text || '').trim();
  if (!text) return { isGhost: true, reason: 'emptyLine', dropCountKey: 'ghostEmptyLineDrop' };

  const compact = text.replace(/\s+/g, '');
  const compactUpper = compact.toUpperCase();
  if (compactUpper === 'AAAANLWAL') {
    return { isGhost: true, reason: 'garbageHallucination', dropCountKey: 'ghostGarbageHallucinationDrop' };
  }

  const asciiCompact = compact.replace(/[^A-Za-z0-9]/g, '');
  const hasCjkOrThai = /[\u0E00-\u0E7F\u3040-\u30FF\u4E00-\u9FFF\uAC00-\uD7AF]/.test(compact);

  // A. Pure symbol/punctuation noise generated by spiky balloon edges
  const isPureSymbolNoise = !hasCjkOrThai && asciiCompact.length === 0;
  if (isPureSymbolNoise) {
    return { isGhost: true, reason: 'pureSymbolNoise', dropCountKey: 'ghostPureSymbolNoiseDrop' };
  }

  // B. Repetitive vertical lines, slashes, or symbol junk
  const isVerticalLineJunk = !hasCjkOrThai && /^[lI|!/\\_\-]+$/i.test(compact) && !/^[IAO]$/i.test(asciiCompact);
  if (isVerticalLineJunk) {
    return { isGhost: true, reason: 'verticalLineJunk', dropCountKey: 'ghostVerticalLineJunkDrop' };
  }

  // C. Single-character junk
  const isSingleCharJunk = !hasCjkOrThai
    && asciiCompact.length === 1
    && !/[a-zA-Z0-9]/.test(asciiCompact);
  if (isSingleCharJunk) {
    return { isGhost: true, reason: 'singleCharJunk', dropCountKey: 'ghostSingleCharJunkDrop' };
  }

  // D. Tiny noise junk boxes
  const bbox = line.bbox;
  if (bbox) {
    const width = Math.max(1, Number(bbox.x1 || 0) - Number(bbox.x0 || 0));
    const height = Math.max(1, Number(bbox.y1 || 0) - Number(bbox.y0 || 0));
    const area = width * height;

    const validWords = (Array.isArray(line.words) ? line.words : []).filter((w) => {
      const wt = String(w?.text || '').trim();
      const wb = w?.bbox;
      if (!wt || !wb) return false;
      return (wb.x1 - wb.x0) > 0 && (wb.y1 - wb.y0) > 0;
    });

    const confidenceSamples = validWords.length > 0
      ? validWords.map((w) => Number(w.confidence || 0))
      : [Number(line.confidence || 0)];
    const avgConfidence = confidenceSamples.reduce((sum, v) => sum + v, 0) / Math.max(1, confidenceSamples.length);

    const isKnownShortWord = isKnownShortWordHelper(asciiCompact);
    const containsAlphanumeric = /[a-zA-Z0-9]/.test(asciiCompact);
    const isTinyJunkBox = !hasCjkOrThai
      && asciiCompact.length <= 3
      && area <= 8000 * dpiScale * dpiScale
      && (containsAlphanumeric
        ? (isExternal ? avgConfidence <= 85 : avgConfidence <= 75)
        : (isExternal ? avgConfidence <= 98 : avgConfidence <= 85)
      )
      && !isKnownShortWord;

    if (isTinyJunkBox) {
      return { isGhost: true, reason: 'tinyJunkBox', dropCountKey: 'ghostTinyJunkBoxDrop' };
    }
  }

  // E. Watermark/bracket junk
  if (/[\?\[\(\{\}\)\]]{2,}/.test(compact) && /help/i.test(compact)) {
    return { isGhost: true, reason: 'watermarkBracketJunk', dropCountKey: 'ghostWatermarkJunkDrop' };
  }

  return { isGhost: false };
}

/**
 * Surgery Targeted Filter for PaddleOCR/EasyOCR Ghost Border Noise Artifacts
 */
export const filterGhostOcrData = (
  lines: OCRLine[],
  words: OCRWord[],
  engine: OCREngine,
  dpi: number = 300
): GhostFilterResult => {
  const ocrEngine = String(engine || '').toLowerCase();
  const isExternal = ocrEngine === 'paddleocr' || ocrEngine === 'easyocr';
  const dpiScale = Math.max(0.2, dpi / 300);

  const dropCounts: Record<string, number> = {};
  const droppedWords: OCRDroppedWord[] = [];

  // 1. Clean and filter ghost noise lines
  const filteredLines = (lines || []).filter((line) => {
    const check = checkGhostNoiseReason(line, isExternal, dpiScale);
    if (check.isGhost) {
      if (check.dropCountKey) {
        dropCounts[check.dropCountKey] = (dropCounts[check.dropCountKey] || 0) + 1;
      }
      droppedWords.push({
        filter: 'ghostFilter',
        reason: check.reason || 'ghostNoise',
        text: String(line?.text || '').trim(),
        confidence: Number(line?.confidence || 0),
        bbox: line?.bbox,
      });
      return false;
    }
    return true;
  });

  // 2. Filter words array using bboxes of remaining active lines to ensure overlays and DB sync perfectly
  const remainingWords: OCRWord[] = [];
  const remainingWordBboxes = new Set<string>();

  filteredLines.forEach((line) => {
    if (Array.isArray(line.words)) {
      line.words.forEach((w) => {
        if (w && w.bbox) {
          const key = `${w.bbox.x0.toFixed(1)}:${w.bbox.y0.toFixed(1)}:${w.bbox.x1.toFixed(1)}:${w.bbox.y1.toFixed(1)}`;
          remainingWordBboxes.add(key);
        }
      });
    }
  });

  if (Array.isArray(words)) {
    words.forEach((w) => {
      if (w && w.bbox) {
        const key = `${w.bbox.x0.toFixed(1)}:${w.bbox.y0.toFixed(1)}:${w.bbox.x1.toFixed(1)}:${w.bbox.y1.toFixed(1)}`;
        if (remainingWordBboxes.has(key)) {
          remainingWords.push(w);
        }
      }
    });
  }

  return {
    lines: filteredLines,
    words: remainingWords,
    droppedWords,
    dropCounts,
  };
};
