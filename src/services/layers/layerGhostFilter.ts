/**
 * Layer Ghost Filter Service
 * 
 * Centralized filter to purge phantom OCR noise, spiky speech balloon border artifacts,
 * and isolated punctuation debris from TextLayers in both Canvas Overlays and LayerPanel.
 */

import type { TextLayer } from '../../types/layers';
import { isKnownShortWordHelper } from '../ocr/ocrSafetyLineDedup';
import { lookupShortPhraseTh } from '../translation/offlineTranslationService';

/**
 * Checks whether a given TextLayer is ghost/noise artifact.
 *
 * @param layer The TextLayer to inspect
 * @param thaiLayers Optional list of visible Thai layers on the same page for overlap detection
 * @returns true if the layer is considered noise/ghost artifact, false otherwise
 */
export function isGhostTextLayer(layer: TextLayer, thaiLayers: TextLayer[] = []): boolean {
  if (!layer) return true;
  
  // 1. Explicit user edits are always protected
  if (layer.userEdited) return false;

  const sourceText = String(layer.sourceText || '').trim();
  const currentText = String(layer.text || '').trim();
  const text = sourceText || currentText;
  if (!text) return true;

  const compact = text.replace(/\s+/g, '');
  const compactUpper = compact.toUpperCase();
  if (compactUpper === 'AAAANLWAL') return true; // Known OCR hallucination junk

  // Detect phantom "BELIEVE" OCR ghost overlapping with actual Thai text
  if (compactUpper === 'BELIEVE' && thaiLayers.length > 0) {
    const hasOverlapWithThai = thaiLayers.some((thaiLayer) => {
      if (!layer.bbox || !thaiLayer.bbox) return false;
      const areaA = (layer.bbox.x1 - layer.bbox.x0) * (layer.bbox.y1 - layer.bbox.y0);
      if (areaA <= 0) return false;

      const interX0 = Math.max(layer.bbox.x0, thaiLayer.bbox.x0);
      const interY0 = Math.max(layer.bbox.y0, thaiLayer.bbox.y0);
      const interX1 = Math.min(layer.bbox.x1, thaiLayer.bbox.x1);
      const interY1 = Math.min(layer.bbox.y1, thaiLayer.bbox.y1);

      const interArea = Math.max(0, interX1 - interX0) * Math.max(0, interY1 - interY0);
      return (interArea / areaA) >= 0.7;
    });
    if (hasOverlapWithThai) {
      return true;
    }
  }

  const asciiCompact = compact.replace(/[^A-Za-z0-9]/g, '');
  const hasCjkOrThai = /[\u0E00-\u0E7F\u3040-\u30FF\u4E00-\u9FFF\uAC00-\uD7AF]/.test(sourceText)
    || /[\u0E00-\u0E7F\u3040-\u30FF\u4E00-\u9FFF\uAC00-\uD7AF]/.test(currentText);

  // A. Pure symbol/punctuation noise generated by spiky balloon edges
  const isPureSymbolNoise = !hasCjkOrThai && asciiCompact.length === 0;
  if (isPureSymbolNoise) return true;

  // B. Repetitive vertical lines, slashes, or symbol junk (e.g. "|||", "///", "lll", "III", "111")
  const isVerticalLineJunk = !hasCjkOrThai && /^[lI1|!/\\_\-]+$/i.test(compact) && !/^[IAO]$/i.test(asciiCompact);
  if (isVerticalLineJunk) return true;

  // C. Single-character junk (letters or digits that aren't common standalone tokens)
  const isSingleCharJunk = !hasCjkOrThai
    && asciiCompact.length === 1
    && !/^[IAO]$/i.test(asciiCompact)
    && !/^[0-9]$/.test(asciiCompact);
  if (isSingleCharJunk) return true;

  // D. Tiny noise junk boxes with very small area and short ascii text
  const bbox = layer.bbox;
  if (bbox) {
    const width = Math.max(1, Number(bbox.x1 || 0) - Number(bbox.x0 || 0));
    const height = Math.max(1, Number(bbox.y1 || 0) - Number(bbox.y0 || 0));
    const area = width * height;

    const isNumber = /^[0-9]+$/.test(asciiCompact);
    const isKnownShortWord = isNumber
      || isKnownShortWordHelper(asciiCompact)
      || Boolean(lookupShortPhraseTh(sourceText))
      || Boolean(lookupShortPhraseTh(currentText))
      || Boolean(lookupShortPhraseTh(asciiCompact));

    const isTinyJunkBox = !hasCjkOrThai
      && !isNumber
      && asciiCompact.length <= 3
      && area <= 8000
      && !isKnownShortWord;

    if (isTinyJunkBox) return true;
  }

  return false;
}

/**
 * Filter an array of TextLayers, removing ghost noise while protecting valid dialogue and user edits.
 *
 * @param layers Array of TextLayers to filter
 * @returns Filtered TextLayers
 */
export function filterGhostTextLayers(layers: TextLayer[]): TextLayer[] {
  if (!Array.isArray(layers) || layers.length === 0) return [];
  const thaiLayers = layers.filter((l) =>
    l && l.visible && /[\u0E00-\u0E7F]/.test(String(l.text || ''))
  );
  return layers.filter((layer) => !isGhostTextLayer(layer, thaiLayers));
}
